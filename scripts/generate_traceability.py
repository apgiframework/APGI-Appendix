#!/usr/bin/env python3
"""Render docs/REQUIREMENTS_TRACEABILITY.md from the contracts/*.json registers.

Run with --check to fail when the committed document is stale.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs/REQUIREMENTS_TRACEABILITY.md"


def cell(s) -> str:
    return str(s if s is not None else "-").replace("|", "\\|").replace("\n", " ")


def render() -> str:
    load = lambda n: json.loads((ROOT / "contracts" / n).read_text())
    profile, tasks = load("application-validation-profile.json"), load("task-register.json")
    lines = [
        "# Requirements traceability (generated)",
        "",
        "Generated by `scripts/generate_traceability.py` from `contracts/*.json`. Do not edit by hand.",
        "Profile status: **" + profile["profile_status"] + "**. Nothing here claims scientific parity or release readiness.",
        "",
        "## A08 validation-spec requirements (APGI-VAL-SPEC-1.2, matrix 5.2)",
        "",
        "| Requirement | Applies | Status | Evidence | Remaining work |",
        "|---|---|---|---|---|",
    ]
    for r in profile["requirements"]:
        if r["applicability"] == "NOT_APPLICABLE":
            continue
        lines.append(f"| {r['id']} | {r['applicability']} | {r['status']} | {cell(r['evidence'])} | {cell(r['gap'])} |")
    na = [r["id"] for r in profile["requirements"] if r["applicability"] == "NOT_APPLICABLE"]
    lines += ["", "Not applicable to A08 per matrix 5.2 (approver pending): " + ", ".join(na) + ".", "",
              "## Appendix task register (43 rows)", "",
              "| Task | Description | Status | External dependency |", "|---|---|---|---|"]
    for t in tasks["tasks"]:
        lines.append(f"| {t['id']} | {cell(t['task'])} | {cell(t['status'])} | {cell(t['external_dependency'])} |")
    return "\n".join(lines) + "\n"


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print("FAIL: docs/REQUIREMENTS_TRACEABILITY.md is stale; run scripts/generate_traceability.py")
            return 1
        print("Traceability document is current.")
        return 0
    OUT.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
